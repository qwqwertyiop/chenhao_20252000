// ============================================================
// Complex.h - Complex 复数类声明
// 主题：演示类、构造函数、运算符重载
// ============================================================

#ifndef COMPLEX_H
#define COMPLEX_H

// ============================================================
// 类定义：Complex 复数类
// ============================================================
class Complex {
private:
    // ---- 私有成员变量（属性）----
    double real;  // 实部
    double imag;  // 虚部

public:
    // ========================================================
    // 构造函数：创建对象时自动调用，用来初始化
    // 函数名和类名相同，没有返回值
    // 默认参数只在声明中写一次
    // ========================================================
    Complex(double r = 0, double i = 0);

    // ========================================================
    // 运算符重载：让 Complex 对象也能用 + 号相加
    // operator+ 是函数名，参数是另一个 Complex 对象
    // ========================================================
    Complex operator+(const Complex& other) const;

    // ========================================================
    // 运算符重载：让 Complex 对象也能用 - 号相减
    // ========================================================
    Complex operator-(const Complex& other) const;

    // ========================================================
    // 成员函数：打印复数
    // ========================================================
    void print() const;

    // ========================================================
    // Getter 函数：获取实部和虚部
    // 因为 real 和 imag 是 private，外部不能直接访问
    // 所以提供 public 的 getter 函数
    // ========================================================
    double getReal() const;
    double getImag() const;
};

#endif
